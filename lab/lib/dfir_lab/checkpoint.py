"""dfir-lab checkpoint / hint / progress (spec 5.4).

checkpoints.json (generated by dfir-lab-make-checkpoints):
{
  "format": 1,
  "case": "<case id>",
  "checkpoints": [
    {"id": 1, "title": "...", "question": "...",
     "normalize": "integer",            # or exact|casefold|ip|timestamp-utc-seconds|regex-extract
     "pattern": null, "then": null,     # for regex-extract
     "salt": "<hex>", "hash": "<sha256(salt + normalised answer)>",
     "alternates": ["<sha256(salt + alternate)>", ...],
     "hints": ["...", "..."],
     "success": "..."}
  ]
}
Answers are never stored in clear, not in the kit and not in progress.json.
"""

import hashlib
import hmac
import json

from . import fsutil, paths, ui
from .errors import LabError, UsageError
from .normalize import FormatProblem, normalize


def answer_hash(salt, normalised):
    return hashlib.sha256((salt + normalised).encode("utf-8")).hexdigest()


def load(cfg):
    path = cfg.case_path("checkpoints")
    if not path or not path.is_file():
        raise LabError("The checkpoint file %s is missing." % path,
                       "The case kit is incomplete. Tell the TA.", code=3)
    try:
        with open(path, encoding="utf-8") as fh:
            data = json.load(fh)
        cps = data["checkpoints"]
        if not isinstance(cps, list):
            raise TypeError
    except (OSError, ValueError, KeyError, TypeError):
        raise LabError("The checkpoint file %s is damaged." % path,
                       "Tell the TA; the case kit needs to be rebuilt.", code=3)
    return {str(cp["id"]): cp for cp in cps if isinstance(cp, dict) and "id" in cp}


def _find(cps, n):
    key = str(n).strip()
    if key not in cps:
        ids = ", ".join(sorted(cps, key=lambda k: (len(k), k)))
        raise UsageError("There is no checkpoint %r. The checkpoints are: %s." % (key, ids),
                         "Example: dfir-lab checkpoint 1 4625")
    return cps[key]


def load_progress(cfg):
    data = fsutil.read_json(paths.progress_file(), default=None)
    if not isinstance(data, dict) or data.get("case") != cfg.case_id:
        if isinstance(data, dict) and data.get("case") and data.get("case") != cfg.case_id:
            # Keep the other case's progress next to it rather than losing it.
            try:
                paths.progress_file().rename(paths.progress_file().with_name(
                    "progress-%s.json" % data.get("case")))
            except OSError:
                pass
        data = {"case": cfg.case_id, "checkpoints": {}}
    data.setdefault("checkpoints", {})
    return data


def save_progress(data):
    fsutil.write_json_atomic(paths.progress_file(), data)


def _entry(progress, cid):
    return progress["checkpoints"].setdefault(str(cid), {
        "attempts": 0, "solved": False, "solved_at": None, "first_attempt_at": None,
        "hints_used": 0, "history": [],
    })


def is_correct(cp, answer):
    """Returns True/False; raises FormatProblem for a badly formed answer."""
    norm = normalize(cp.get("normalize", "exact"), answer, cp.get("pattern"), cp.get("then"))
    h = answer_hash(cp["salt"], norm)
    targets = [cp["hash"]] + list(cp.get("alternates") or [])
    return any(hmac.compare_digest(h, t) for t in targets)


def run_checkpoint(cfg, n, answer_words):
    cps = load(cfg)
    cp = _find(cps, n)
    answer = " ".join(answer_words or []).strip()
    if not answer:
        ui.out("Checkpoint %s: %s" % (cp["id"], cp.get("title", "")))
        ui.out(cp.get("question", ""))
        answer = ui.ask_text("Your answer:", title="Checkpoint %s" % cp["id"]) or ""
        if not answer.strip():
            raise UsageError("No answer was given.", "Example: dfir-lab checkpoint %s <answer>"
                             % cp["id"])
    try:
        ok = is_correct(cp, answer)
    except FormatProblem as exc:
        ui.out("Checkpoint %s: that answer is not in the expected form. %s" % (cp["id"], exc))
        ui.out("This did not count as an attempt.")
        return 1
    progress = load_progress(cfg)
    e = _entry(progress, cp["id"])
    now = fsutil.utc_iso()
    e["attempts"] += 1
    e["first_attempt_at"] = e["first_attempt_at"] or now
    e["history"].append({"time": now, "correct": ok, "hints_used": e["hints_used"]})
    already = e["solved"]
    if ok and not already:
        e["solved"] = True
        e["solved_at"] = now
    save_progress(progress)
    fsutil.log("checkpoint", id=str(cp["id"]), correct=ok, attempts=e["attempts"])
    if ok:
        ui.out("Checkpoint %s: CORRECT." % cp["id"])
        if cp.get("success"):
            ui.out(cp["success"])
        return 0
    ui.out("Checkpoint %s: not correct (attempt %d)." % (cp["id"], e["attempts"]))
    remaining = len(cp.get("hints") or []) - e["hints_used"]
    if remaining > 0:
        ui.out("Stuck? Get a hint with: dfir-lab hint %s  (%d left)" % (cp["id"], remaining))
    return 1


def run_hint(cfg, n):
    cps = load(cfg)
    cp = _find(cps, n)
    hints = cp.get("hints") or []
    progress = load_progress(cfg)
    e = _entry(progress, cp["id"])
    if e["hints_used"] >= len(hints):
        ui.out("Checkpoint %s has no more hints (you have seen all %d)." % (cp["id"], len(hints)))
        for i, h in enumerate(hints, 1):
            ui.out("  Hint %d: %s" % (i, h))
        if not hints:
            ui.out("Ask your partner or the TA.")
        return 0
    e["hints_used"] += 1
    save_progress(progress)
    fsutil.log("hint", id=str(cp["id"]), used=e["hints_used"])
    ui.out("Checkpoint %s, hint %d of %d:" % (cp["id"], e["hints_used"], len(hints)))
    ui.out("  " + hints[e["hints_used"] - 1])
    return 0


def run_progress(cfg):
    cps = load(cfg)
    progress = load_progress(cfg)
    rows = []
    done = 0
    for cid in sorted(cps, key=lambda k: (len(k), k)):
        cp = cps[cid]
        e = progress["checkpoints"].get(cid, {})
        solved = bool(e.get("solved"))
        done += solved
        rows.append([cid, cp.get("title", "")[:40], "done" if solved else "-",
                     e.get("attempts", 0), "%d/%d" % (e.get("hints_used", 0),
                                                      len(cp.get("hints") or []))])
    ui.out("Progress for case %s" % cfg.case_title)
    ui.out(ui.table(rows, ["#", "Checkpoint", "Status", "Attempts", "Hints"]))
    ui.out("%d of %d checkpoints done." % (done, len(cps)))
    return 0
